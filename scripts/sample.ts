// The sample: our own six apps (their real package-lock.json files) checked against CVE-2026-119348, the Next.js
// advisory published on 19 Nov 2026. Writes a frozen copy for the app and the templates' sample values.
// Run: node --experimental-strip-types scripts/sample.ts
import { readFileSync, writeFileSync } from "node:fs";
import { decide, readAdvisory, readLock, toValues, type Pkg } from "../templates/_shared/vex.ts";

const ADVISORY = "CVE-2026-119348";
const DATE = "2026-11-20";
const APPS: Array<[string, string]> = [["Sundown", "02-sundown"], ["Fineprint", "03-fineprint"], ["Plainspeed", "04-plainspeed"], ["Owed", "05-owed"], ["Columnist", "06-columnist"], ["Runway", "07-runway"]];

const osv = (id: string) => fetch(`https://api.osv.dev/v1/vulns/${id}`).then((r) => r.json());
const first = await osv(ADVISORY);
const records = [first, ...(await Promise.all((first.aliases ?? []).filter((a: string) => a.startsWith("GHSA-")).map(osv)))];
const adv = readAdvisory(records);

const products = APPS.map(([name, dir]) => {
  const file = new URL(`../../${dir}/package-lock.json`, import.meta.url);
  const lock = JSON.parse(readFileSync(file, "utf8"));
  return { name, version: lock.version as string | undefined, lockfile: "package-lock.json", packages: readLock("package-lock.json", readFileSync(file, "utf8")) };
});
// Ask OSV about the exact versions of the advisory's packages that the products use.
const names = new Set(adv.packages.map((p) => `${p.ecosystem}:${p.name}`));
const asked = [...new Map(products.flatMap((p) => p.packages).filter((p) => names.has(`${p.ecosystem}:${p.name}`)).map((p) => [`${p.name}@${p.version}`, p])).values()];
const batch = await fetch("https://api.osv.dev/v1/querybatch", { method: "POST", body: JSON.stringify({ queries: asked.map((p) => ({ package: { name: p.name, ecosystem: p.ecosystem }, version: p.version })) }) }).then((r) => r.json());
const hits: Record<string, string[]> = Object.fromEntries(asked.map((p, i) => [`${p.name}@${p.version}`, (batch.results[i].vulns ?? []).map((v: { id: string }) => v.id)]));
const ids = new Set([adv.id, ...adv.aliases]);
const isAffected = (p: Pkg) => (hits[`${p.name}@${p.version}`] ?? []).some((v) => ids.has(v));

writeFileSync(new URL(`../public/samples/our-apps-${DATE}.json`, import.meta.url), JSON.stringify({ read: DATE, advisory: records, products, hits }) + "\n");
const rows = products.map((p) => ({ name: p.name, version: p.version, verdict: decide(p.packages, adv, isAffected) }));
const values = toValues(adv, rows, { vendor: "rohit-jsfreaky", contact: "github.com/rohit-jsfreaky", date: DATE, signer: "Security contact, rohit-jsfreaky", customer: "Northwind Labs" });
const json = JSON.stringify(values, null, 2);
writeFileSync(new URL("../docs/nextjs.json", import.meta.url), `${json}\n`);
writeFileSync(
  new URL("../templates/_shared/example.ts", import.meta.url),
  `// The sample: CVE-2026-119348 (Next.js, 19 Nov 2026) checked against our own six apps' package-lock.json files\n// on ${DATE}, verdicts from OSV. Generated by scripts/sample.ts. "Northwind Labs" (the customer) is made up.\nconst example = ${json};\n\nexport default example;\n`,
);
console.log(adv.id, adv.aliases, adv.packages.map((p) => p.name), rows.map((r) => `${r.name}:${r.verdict.status}:${r.verdict.found.map((f) => f.version)}`));
